// Package emailtemplates builds the Supabase Auth sign-in email templates in
// many languages from one English source (supabase/templates/source.json).
//
// Supabase renders templates with Go templates and exposes the user's
// metadata as .Data; the app stores the person's main display language there
// as "lang". The generated templates branch on it and fall back to English.
// Translation happens once, when the templates are generated
// (`tool email-templates`), not when an email is sent.
package emailtemplates

import (
	"encoding/json"
	"fmt"
	"html"
	"os"
	"regexp"
	"slices"
	"strings"

	"github.com/shrujancheruku/issho/backend/internal/platform/i18n"
)

// Keys are the strings every language must have.
var Keys = []string{"subject", "heading", "expiry", "ignore"}

// Source is supabase/templates/source.json.
type Source struct {
	Languages []string          `json:"languages"`
	Strings   map[string]string `json:"strings"`
}

// ReadSource reads and checks the source file.
func ReadSource(path string) (Source, error) {
	var s Source
	raw, err := os.ReadFile(path)
	if err != nil {
		return s, err
	}
	if err := json.Unmarshal(raw, &s); err != nil {
		return s, fmt.Errorf("%s: %w", path, err)
	}
	for _, k := range Keys {
		if strings.TrimSpace(s.Strings[k]) == "" {
			return s, fmt.Errorf("%s: missing string %q", path, k)
		}
	}
	for _, l := range s.Languages {
		if !i18n.ValidDisplay(l) || l == i18n.Authoring {
			return s, fmt.Errorf("%s: %q is not a language to translate into", path, l)
		}
	}
	return s, nil
}

// Text is the strings in one language, by key.
type Text map[string]string

// rtl languages get dir="rtl" so the paragraph reads right to left.
var rtl = []string{"ar", "he", "fa", "ur", "yi", "ps", "sd", "ug"}

// langVar reads .Data.lang into $lang. Every step is guarded: a user without
// metadata, or with a lang that isn't a string (metadata is editable by its
// owner), must still get an email, in English.
const langVar = `{{- $lang := "" -}}{{- with .Data -}}{{- with .lang -}}{{- $lang = printf "%v" . -}}{{- end -}}{{- end -}}`

// check rejects translations that could break the template or the TOML they
// land in.
func check(lang string, t Text) error {
	for _, k := range Keys {
		v := t[k]
		if strings.TrimSpace(v) == "" {
			return fmt.Errorf("%s: no %q", lang, k)
		}
		if strings.Contains(v, "{{") || strings.Contains(v, "}}") || strings.Contains(v, "'''") || strings.ContainsAny(v, "\n\r") {
			return fmt.Errorf("%s: %q contains template or TOML syntax: %q", lang, k, v)
		}
	}
	return nil
}

func block(lang string, t Text) string {
	dir := ""
	if slices.Contains(rtl, lang) {
		dir = ` dir="rtl"`
	}
	e := html.EscapeString
	return fmt.Sprintf(`<div lang="%s"%s style="font-family: -apple-system, 'Helvetica Neue', 'Hiragino Sans', 'Noto Sans', sans-serif; max-width: 420px; margin: 0 auto; padding: 24px; color: #111111;">
  <p style="font-size: 18px; margin: 0 0 16px;">%s</p>
  <p style="font-size: 36px; letter-spacing: 8px; font-weight: 700; margin: 0 0 16px; color: #BC002D;" dir="ltr">{{ .Token }}</p>
  <p style="font-size: 14px; color: #555555; margin: 0;">%s %s</p>
</div>`, lang, dir, e(t["heading"]), e(t["expiry"]), e(t["ignore"]))
}

// branches renders one {{ if }} chain over the languages, English last.
func branches(langs []string, tr map[string]Text, english Text, each func(lang string, t Text) string) string {
	var b strings.Builder
	for i, l := range langs {
		kw := "else if"
		if i == 0 {
			kw = "if"
		}
		fmt.Fprintf(&b, "{{- %s eq $lang %q }}%s", kw, l, each(l, tr[l]))
	}
	if len(langs) > 0 {
		b.WriteString("{{- else }}")
	}
	b.WriteString(each(i18n.Authoring, english))
	if len(langs) > 0 {
		b.WriteString("{{- end }}")
	}
	return b.String()
}

// Render returns the email body template and the subject template. tr holds
// every language in langs.
func Render(src Source, tr map[string]Text) (body, subject string, err error) {
	english := Text(src.Strings)
	if err := check(i18n.Authoring, english); err != nil {
		return "", "", err
	}
	for _, l := range src.Languages {
		if err := check(l, tr[l]); err != nil {
			return "", "", err
		}
	}
	body = "<!-- Generated by `tool email-templates` from supabase/templates/source.json: edit that, not this file. -->\n" +
		"<!-- Issho sign-in code, in the language stored in the user's metadata (\"lang\"). The app asks for the code: no links, which can't open the native app reliably. -->\n" +
		langVar + "\n" +
		branches(src.Languages, tr, english, func(l string, t Text) string { return "\n" + block(l, t) + "\n" }) + "\n"
	subject = langVar + branches(src.Languages, tr, english, func(_ string, t Text) string { return t["subject"] })
	return body, subject, nil
}

var subjectLine = regexp.MustCompile(`(?m)^(\[auth\.email\.template\.(?:magic_link|confirmation)\]\n)subject = .*$`)

// SetSubjects replaces the subject of the sign-in templates in a Supabase
// config.toml. The subject is a TOML literal string (no escaping), which
// check guarantees is safe.
func SetSubjects(config, subject string) (string, error) {
	n := 0
	out := subjectLine.ReplaceAllStringFunc(config, func(m string) string {
		n++
		header := subjectLine.FindStringSubmatch(m)[1]
		return header + "subject = '''" + subject + "'''"
	})
	if n != 2 {
		return "", fmt.Errorf("config.toml: found %d sign-in template subjects, want 2 (magic_link, confirmation)", n)
	}
	return out, nil
}
