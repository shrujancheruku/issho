package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"log/slog"
	"maps"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"connectrpc.com/connect"

	isshov1 "github.com/shrujancheruku/issho/backend/gen/issho/v1"
	"github.com/shrujancheruku/issho/backend/gen/issho/v1/isshov1connect"
	"github.com/shrujancheruku/issho/backend/internal/cities"
	"github.com/shrujancheruku/issho/backend/internal/platform/i18n"
)

// bundledCatalog is one language's UI text as the app bundles it.
type bundledCatalog struct {
	// CatalogVersion is what the API reported, for the record.
	CatalogVersion string            `json:"catalogVersion"`
	Strings        map[string]string `json:"strings"`
}

// uiBundle writes the UI text of every city's languages, as an API serves
// it (UIService.GetStrings), into the app (apps/mobile/src/i18n/bundled),
// so a fresh install shows them before its first fetch, even offline.
// Taking it from the API, not the database, means the app's first fetch
// replaces it with the same text: run it against the API the app build
// will use. English is bundled already and skipped.
func uiBundle(args []string) error {
	fs := flag.NewFlagSet("ui-bundle", flag.ExitOnError)
	api := fs.String("api", os.Getenv("API_URL"), "the API to take the text from (default $API_URL)")
	packs := fs.String("packs", "../data/citypacks", "city packs; their languages are bundled")
	out := fs.String("out", "../apps/mobile/src/i18n/bundled", "where the files go")
	wait := fs.Duration("wait", 3*time.Minute, "how long to wait for machine translations to finish")
	_ = fs.Parse(args)
	if *api == "" {
		return errors.New("-api (or API_URL) is required: the API the app build will use")
	}
	files, err := filepath.Glob(filepath.Join(*packs, "*.json"))
	if err != nil {
		return err
	}
	langs := map[string]bool{}
	for _, f := range files {
		p, err := cities.ReadPack(f)
		if err != nil {
			return err
		}
		for _, l := range p.Languages {
			if l != i18n.Authoring {
				langs[l] = true
			}
		}
	}
	if len(langs) == 0 {
		return errors.New("no languages other than English in the city packs")
	}

	client := isshov1connect.NewUIServiceClient(http.DefaultClient, strings.TrimRight(*api, "/"))
	ctx := context.Background()
	bundles := map[string]bundledCatalog{}
	for _, lang := range slices.Sorted(maps.Keys(langs)) {
		deadline := time.Now().Add(*wait)
		for {
			res, err := client.GetStrings(ctx, connect.NewRequest(&isshov1.GetStringsRequest{Language: lang}))
			if err != nil {
				return fmt.Errorf("%s: %w", lang, err)
			}
			if res.Msg.Complete {
				bundles[lang] = bundledCatalog{CatalogVersion: res.Msg.CatalogVersion, Strings: res.Msg.Strings}
				slog.Info("bundled", "lang", lang, "strings", len(res.Msg.Strings), "version", res.Msg.CatalogVersion)
				break
			}
			if time.Now().After(deadline) {
				return fmt.Errorf("%s: machine translations still running after %s; nothing written (re-run)", lang, *wait)
			}
			time.Sleep(5 * time.Second)
		}
	}

	if err := os.MkdirAll(*out, 0o755); err != nil {
		return err
	}
	old, _ := filepath.Glob(filepath.Join(*out, "*.json"))
	for _, f := range old {
		if !langs[strings.TrimSuffix(filepath.Base(f), ".json")] {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	var index bytes.Buffer
	index.WriteString("// Generated by `make ui-bundle` (backend/cmd/tool/uibundle.go): the UI text\n" +
		"// of the city packs' languages, shown before the first fetch. Don't edit.\n")
	for _, lang := range slices.Sorted(maps.Keys(bundles)) {
		var b bytes.Buffer
		enc := json.NewEncoder(&b)
		enc.SetEscapeHTML(false)
		enc.SetIndent("", "  ")
		if err := enc.Encode(bundles[lang]); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(*out, lang+".json"), b.Bytes(), 0o644); err != nil {
			return err
		}
		fmt.Fprintf(&index, "import %s from './%s.json';\n", lang, lang)
	}
	index.WriteString("\nexport type BundledCatalog = { catalogVersion: string; strings: Record<string, string> };\n\n")
	fmt.Fprintf(&index, "export const bundled: Readonly<Record<string, BundledCatalog>> = { %s };\n",
		strings.Join(slices.Sorted(maps.Keys(bundles)), ", "))
	return os.WriteFile(filepath.Join(*out, "index.ts"), index.Bytes(), 0o644)
}
